def glyph(ch):
    return G.get(ch.upper(), G["?"])


def text_width(s, spacing=1):
    return len(s) * (5 + spacing) - spacing


def draw_text(arr, s, x, y, col, spacing=1, scale=1):
    """Blit text into an art canvas (used for neon signs and posters)."""
    cx = x
    for ch in s:
        rows = glyph(ch)
        for gy, row in enumerate(rows):
            for gx, c in enumerate(row):
                if c == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            put(arr, cx + gx * scale + sx, y + gy * scale + sy, col)
        cx += (5 + spacing) * scale


def font_sheet():
    out = canvas(CELL_W * len(GLYPH_ORDER), CELL_H)
    for i, ch in enumerate(GLYPH_ORDER):
        for gy, row in enumerate(G[ch]):
            for gx, c in enumerate(row):
                if c == "#":
                    out[gy, i * CELL_W + gx] = (255, 255, 255, 255)
    return out


def button_sprite(w, h, ramp):
    """Chunky bevelled button: lit top, dark lip at the bottom, 1px rounded corners."""
    out = canvas(w, h + 2)
    for y in range(h + 2):
        for x in range(w):
            corner = (x in (0, w - 1)) and (y in (0, h + 1))
            if corner:
                continue
            if y >= h:
                col = P(ramp, 0)                     # bottom lip (the "press" depth)
            elif x in (0, w - 1) or y == 0 or y == h - 1:
                col = P(ramp, 1)
            elif y == 1:
                col = P(ramp, -1)
            elif y < h * 0.5:
                col = P(ramp, -2)
            else:
                col = P(ramp, -3) if bayer(x, y) > 0.5 or y > h * 0.7 else P(ramp, -2)
            out[y, x] = col
    return out


def white_pixel():
    out = canvas(4, 4)
    out[:] = (255, 255, 255, 255)
    return out


def soft_light(size, falloff=2.0):
    """Radial light blob, smooth alpha (used additively for light pools and glows)."""
    out = canvas(size, size)
    c = (size - 1) / 2
    for y in range(size):
        for x in range(size):
            d = ((x - c) ** 2 + (y - c) ** 2) ** 0.5 / c
            if d < 1:
                a = (1 - d) ** falloff
                out[y, x] = (255, 255, 255, int(255 * a))
    return out


def cone_light(w, h):
    """Headlight beam: wide toward +x, fading with distance and toward the edges."""
    out = canvas(w, h)
    for y in range(h):
        for x in range(w):
            t = x / (w - 1)
            half = 0.12 + 0.88 * t
            v = abs((y - (h - 1) / 2) / ((h - 1) / 2))
            if v < half:
                edge = 1 - (v / half) ** 2
                a = edge * (1 - t) ** 1.4 * min(1.0, t * 8)
                out[y, x] = (255, 255, 255, int(255 * a))
    return out


